                    <div class="card-body">
                        <h2 class="card-title pt-3 ps-2 pe-2 pb-5 text-center">Política de Privacidade e Proteção de
                            Dados Pessoais | Instituições Ensino Lusófona em Portugal</h2>
                        <div class="card-text ps-2 pe-2">

                            <ol>
                                <li>A recolha e armazenamento dos dados pessoais da Universidade Lusófona, ISDOM-
                                    Instituto Superior Dom Dinis, ISLA Gaia, IPLUSO – Instituto Politécnico da
                                    Lusofonia, ETACADEMY – Executive Training Academy e o ISMAT- Instituto Superior
                                    Manuel Teixeira Gomes é efetuada pela entidade instituidora do estabelecimento de
                                    ensino que é o responsável pelo tratamento dos dados, garantindo-se a segurança das
                                    bases, através de políticas e medidas adequadas para evitar acessos e utilizações
                                    indevidas e para responder a eventuais intrusões, minimizando os possíveis efeitos.
                                </li><br>
                                <li>No âmbito das candidaturas e na relação estudante/instituição, e por força de
                                    obrigação legal, os serviços e órgãos competentes, recolhem, tratam e arquivam os
                                    dados pessoais necessários aos processos e os documentos entregues, quer em formato
                                    físico quer em formato digital.</li>
                                <ol>
                                    <li>No âmbito da subscrição de informação, os dados são recolhidos e tratados com a
                                        finalidade de comunicação com os interessados, mediante as suas preferências, e
                                        armazenados em base digital.</li>
                                </ol><br>
                                <li>O tratamento da informação e direito do titular à alteração dos dados:</li>
                                <ol>
                                    <li>Candidaturas:</li>
                                    <ol>
                                        <li>Os dados recolhidos são tratados no âmbito do processo de candidatura e é
                                            válida durante o período de análise e decisão, nunca o tempo de arquivo
                                            excedendo um ano, sendo:</li>
                                        <ol>
                                            <li>No caso de candidaturas validadas e aceites, os dados transferidos e
                                                arquivados no processo individual de aluno, não se procedendo à
                                                eliminação dos mesmos;</li>
                                            <li>No caso de candidaturas não admitidas, a informação é arquivada por um
                                                período máximo de 5 anos, não podendo os dados ser alterados ou
                                                eliminados antes desse período;</li>
                                            <li>Nos restantes casos, nomeadamente candidaturas não validadas, os dados
                                                são armazenados, no máximo, por um período de 1 ano, findo o qual são
                                                eliminados.</li>
                                        </ol>
                                    </ol>
                                    <li>Matrícula/Inscrição&nbsp;(Processo Individual de Aluno)</li>
                                    <ol>
                                        <li>Os dados recolhidos são tratados no âmbito do processo escolar, sendo a
                                            informação guardada de forma permanente, em meio físico e digital, não
                                            havendo lugar à sua destruição (ou esquecimento).</li>
                                        <li>Os dados de candidaturas validadas e aceites, cujos titulares se inscrevam,
                                            são transferidos para o processo de estudante, não podendo ser alterados e/o
                                            eliminados.</li>
                                    </ol>
                                    <li>Subscrição de comunicação e informação / Interessados&nbsp;</li>
                                    <ol>
                                        <li>Para efeitos comunicacionais, devidamente autorizado pelos subscritores, são
                                            recolhidos o nome e endereço de correio eletrónico, podendo ser ainda
                                            indicadas áreas preferenciais adequando a oferta de informações aos
                                            interessados.</li>
                                        <li>O tratamento dos dados para efeitos comunicacionais é efetuado em base de
                                            dados digital, por um período de 5 anos, podendo ser renovada a autorização
                                            por igual período.</li>
                                    </ol>
                                </ol><br>
                                <li>Dados incluídos em processos de estudantes, docentes e funcionários:</li>
                                <ol>
                                    <li>Os dados recolhidos e de registo não podem ser esquecidos/apagados, devido à
                                        responsabilidade e necessidade de manutenção dos registos para efeitos de
                                        certificação e cumprimento de obrigações legais, sendo exclusivamente utilizados
                                        para efeitos oficiais, incluindo-se o contacto no âmbito da vida académica e
                                        para avisos necessários e para o cumprimento de obrigações contratuais;</li>
                                    <li>Os dados relativos aos contactos, não sendo esquecidos, são utilizados para
                                        efeitos de gestão processual durante:</li>
                                    <ol>
                                        <li>O período em que a candidatura é válida, sendo esquecidos em momento
                                            posterior e, no máximo, após um ano do registo;</li>
                                        <li>Pelo período em que se mantem a inscrição/matrícula e por um período de 4
                                            anos posteriores à ultima interação do titular com a instituição.</li>
                                    </ol>
                                    <li>O titular dos dados deve, no âmbito das suas obrigações, manter o registo de
                                        dados atualizado, nomeadamente no que respeita aos dados de contacto e/ou
                                        alterações que importem à gestão do processo.</li>
                                    <li>No âmbito dos requisitos legais a instituição promoverá o contacto com o
                                        estudante ou graduado para efeitos de inquéritos, quer académicos quer de
                                        integração laboral</li>
                                </ol><br>
                                <li>Dados recolhidos e gerados no âmbito da atividade pedagógica:</li>
                                <ol>
                                    <li>Os dados pessoais dos estudantes, estritamente necessários ao desempenho das
                                        atividades letivas, como o nome, número e contactos, são disponibilizados aos
                                        docentes para utilização exclusiva no âmbito das atividades;</li>
                                    <li>Os contactos com os estudantes são preferencialmente efetuados por via digital,
                                        quer através de plataforma pedagógica, quer através de contacto por e-mail
                                        institucional;</li>
                                    <li>Os trabalhos e provas realizadas em avaliação contínua, após correção e
                                        classificação, podem ser devolvidos aos estudantes ou conservados pelos docentes
                                        ou em arquivo da instituição pelo período regulamentado (1 ano), sendo
                                        destruídos findo o prazo;</li>
                                    <li>Os trabalhos e provas realizadas em época de exame, após correção e
                                        classificação, são conservados em arquivo da instituição pelo período
                                        regulamentado (3 anos) findo o qual se procede à sua destruição.</li>
                                    <li>Das classificações dos trabalhos e provas realizadas é mantido registo em pauta,
                                        nos termos regulamentares, com indicação do nome e número do estudante e a
                                        respetiva classificação;</li>
                                    <li>As pautas com as classificações dos trabalhos e provas realizadas apenas são
                                        disponibilizadas aos interessados, nomeadamente, e para além dos titulares dos
                                        dados, os restantes estudantes que realizaram prova e dos docentes.</li>
                                    <li>No âmbito da atividade letiva, e nos cursos em que seja necessário, pode ser
                                        efetuada a gravação de registos áudio e vídeo que serão mantidos nos termos dos
                                        números anteriores.</li>
                                    <li>O registo e utilização de imagens e sons dos estudantes, ou de outros elementos
                                        da comunidade académica, noutros âmbitos, incluindo a gravação de aulas e sua
                                        disponibilização pública (não reservada), só pode ocorrer com autorização dos
                                        intervenientes.</li>
                                </ol><br>
                                <li>Dados recolhidos no âmbito de trabalhos académicos e da atividade de investigação.
                                </li>
                                <ol>
                                    <li>Os inquéritos e outros instrumentos de recolha e tratamento de dados no âmbito
                                        de projetos de investigação, quer no âmbito de unidades curriculares, quer de
                                        projetos de investigação, são da responsabilidade dos investigadores e carecem
                                        de informação necessária à compreensão do trabalho a realizar e a utilização a
                                        dar aos dados a recolhe nomeadamente:</li>
                                    <ol>
                                        <li>Apresentação do projeto/trabalho e seus objetivos, justificando a utilização
                                            dos dados a recolher;</li>
                                        <li>Forma, local e duração do armazenamento dos dados recolhidos, incluindo
                                            dados pessoais que possam ser gerados por tratamento de informação, bem como
                                            a forma como o titular possui de aceder aos mesmos e solicitar a sua
                                            alteração ou apagamento;</li>
                                        <li>identificação e contacto do responsável ou responsáveis pelo trabalho e pela
                                            garantia da segurança dos dados, incluindo o(s) orientador(es) no caso de
                                            trabalhos práticos realizados no âmbito de unidades curriculares,
                                            dissertações ou teses;</li>
                                        <li>identificação e contacto do Encarregado da Proteção de Dados;</li>
                                        <li>informação relativa à possibilidade de recurso à CNPD, com o respetivo
                                            contacto.</li>
                                        <li>a autorização expressa e informada do titular dos dados, que inclui as
                                            informações referidas nos pontos anteriores, para a utilização/tratamento
                                            dos dados.</li>
                                    </ol>
                                    <li>Para todos os trabalhos que incluam o tratamento de dados é obrigatória a
                                        existência de uma folha de registo (Modelo EPD_FRI) a disponibilizar pelo EPD e
                                        que acompanha o trabalho, ficando disponível em arquivo pelo menos durante a
                                        manutenção dos dados e podendo/devendo ser disponibilizada aos titulares sempre
                                        que requerida.</li>
                                </ol><br>
                                <li>O titular dos dados não pode requerer o esquecimento/apagamento dos dados de
                                    natureza académica, nomeadamente os resultados de avaliações obtidas e o percurso
                                    escolar, incluindo inscrições, anulações e outros registos do percurso escolar,
                                    sendo armazenados no cumprimento da legislação e das normas regulamentares vigentes,
                                    sendo mantida a garantia de proteção dos dados armazenados.</li><br>
                                <li>A Instituição não fornece, por nenhuma via, os dados recolhidos e armazenados a
                                    entidades terceiras e limita-se a utilizar os dados pessoais de acordo com a
                                    finalidade para que foram recolhidos e autorizada a sua utilização. No entanto, e
                                    decorrente do estatuto de utilidade pública, as entidades oficiais da tutela ou
                                    judiciais que, no âmbito das suas competências, venham a requerer, ou lhes seja
                                    devido por força legal ou regulamentar, o acesso a dados pessoais, casos em que é
                                    efetuada a transmissão dos mesmos, assegurando-se o registo desse ato.</li>
                                <ol>
                                    <li>Em caso de incumprimento contratual a entidade instituidora, reserva-se o
                                        direito de esta transmitir os dados necessários a um representante legal para
                                        efeitos de processo judicial, efetuando-se registo dessa disponibilização e
                                        garantindo-se a transmissão apenas da informação necessária ao processo;</li>
                                    <li>No cumprimento de obrigações legais os dados pessoais e de registo podem ser
                                        transmitidos a autoridade judicial ou entidade estatal oficialmente habilitada,
                                        mediante requerimento, efetuando-se registo dessa disponibilização e
                                        garantindo-se a transmissão apenas da informação necessária ao processo.</li>
                                </ol><br>
                                <li>A política de acesso aos dados na instituição assegura que cada utilizador, no
                                    desempenho das suas funções, apenas acede aos dados estritamente necessários ao
                                    desempenho da sua função, mantendo registo das autorizações de acesso e recorrendo,
                                    sempre que possível, à pseudonimização dos dados, através de código de candidato ou
                                    estudante, minimizando os riscos de violação de privacidade.</li>
                                <ol>
                                    <li>Os funcionários, colaboradores e docentes estão abrangidos por política de
                                        sigilo profissional.</li>
                                    <li>Os dados recolhidos e registados podem ser tratados, de forma anónima, para
                                        análise estatística.</li>
                                </ol><br>
                                <li>No cumprimento do Regulamento Geral da Proteção de Dados, os titulares dos dados têm
                                    garantido o acesso aos dados disponibilizados, podendo consultar, solicitar correção
                                    ou atualização do todo ou de parte dos dados a qualquer momento, incluindo o
                                    esquecimento no que refere aos dados não protegidos e obrigados a conservação nos
                                    termos legais.</li>
                                <ol>
                                    <li>O acesso aos dados é facultado ao seu titular através da utilização do serviço
                                        de secretaria em linha, podendo ser alterados os dados relativos a contactos.
